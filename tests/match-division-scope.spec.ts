import {test,expect,type Page} from "@playwright/test"
import {installScopeAPI} from "./fixtures/match-division-scope"
const results=(page:Page)=>page.getByRole("region",{name:"Search results",exact:true})
async function browse(page:Page){await page.getByRole("button",{name:"Search",exact:true}).click();await expect(results(page)).toBeVisible()}
async function division(page:Page,value:string){await page.getByRole("button",{name:"Division filter",exact:true}).click();await page.getByRole("button",{name:"Division filters",exact:true}).click();await page.getByRole("checkbox",{name:value,exact:true}).check();await page.getByRole("button",{name:"Done",exact:true}).click()}

test("division is discoverable, supports multiple choices, and applies before results and watchlist",async({page})=>{
  const api=await installScopeAPI(page);await page.goto("/match")
  await expect(page.getByLabel("Investigation status",{exact:true})).toHaveValue("completed")
  await division(page,"DPD");await browse(page)
  expect(api.requests.at(-1).filters.divisions).toEqual(["DPD"])
  await expect(results(page).getByRole("heading")).toContainText("of 1 deviation")
  await results(page).locator('button[aria-pressed="false"]').first().click()
  const selected=page.getByRole("complementary",{name:"Selected deviation",exact:true})
  await expect(selected).toContainText("Division: DPD")
  await expect(selected.getByRole("heading",{name:"Retained source text",exact:true})).toBeVisible()
  await selected.getByRole("tab",{name:"Watchlist",exact:true}).click()
  await expect(page.getByRole("tabpanel",{name:"Watchlist",exact:true})).toContainText("DPD")
  expect(api.watchRequests.at(-1)?.searchParams.getAll("divisions")).toEqual(["DPD"])
  expect(api.watchRequests.at(-1)?.searchParams.get("record_scope")).toBe("completed")
  await page.getByRole("button",{name:"Division filters",exact:true}).click();await page.getByRole("checkbox",{name:"DSD",exact:true}).check();await page.getByRole("button",{name:"Done",exact:true}).click();await browse(page)
  expect(api.requests.at(-1).filters.divisions).toEqual(["DPD","DSD"])
  await expect(results(page).getByRole("heading")).toContainText("of 2 deviation")
})
test("ongoing cases show their provisional state and cancelled cases require explicit inclusion",async({page})=>{
  const api=await installScopeAPI(page);await page.goto("/match")
  await page.getByLabel("Investigation status",{exact:true}).selectOption("ongoing");await browse(page)
  await expect(results(page)).toContainText("DEV-OPEN-1");await expect(results(page)).not.toContainText("DEV-CANCEL-1")
  await results(page).locator('button[aria-pressed="false"]').first().click()
  await expect(page.getByRole("complementary",{name:"Selected deviation",exact:true})).toContainText("findings and proposed actions may change")
  await page.getByRole("button",{name:"Filters",exact:true}).click();await page.getByText("More filters · source status, department, dates and CAPA",{exact:true}).click()
  await page.getByRole("checkbox",{name:"Include cancelled deviations",exact:true}).check()
  await expect(page.getByLabel("Investigation status",{exact:true})).toHaveValue("all");await browse(page)
  expect(api.requests.at(-1).filters.include_cancelled).toBe(true);await expect(results(page)).toContainText("DEV-CANCEL-1")
  await results(page).locator('button[aria-pressed]').filter({hasText:"DEV-CANCEL-1"}).click()
  await expect(page.getByRole("complementary",{name:"Selected deviation",exact:true})).toContainText("not a completed investigation precedent")
})
test("an export without ongoing cases gives an honest empty view and clear filters restores completed scope",async({page})=>{
  await installScopeAPI(page,false);await page.goto("/match")
  await page.getByLabel("Investigation status",{exact:true}).selectOption("ongoing")
  await expect(page.getByText(/A source export containing ongoing investigations is needed/)).toBeVisible()
  await page.getByRole("button",{name:"Search",exact:true}).click()
  await expect(page.getByText("No indexed deviations meet the submitted filters. Adjust or clear a filter and try again.",{exact:true})).toBeVisible()
  await page.getByRole("button",{name:"Clear filters",exact:true}).click()
  await expect(page.getByLabel("Investigation status",{exact:true})).toHaveValue("completed")
  await browse(page);await expect(results(page).getByRole("heading")).toContainText("of 4 deviation")
})
